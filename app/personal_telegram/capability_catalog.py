"""Typed operation inventory for C01-C23; availability is never inferred from TL.

This catalogue is review metadata, not a callable raw-RPC registry. A generated
constructor existing in Telethon proves only the pinned library contract.
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class CapabilityRecord:
    id: str
    family: str
    operation: str
    sprint: str
    effect: str
    peer_types: tuple[str, ...]
    methods: tuple[str, ...]
    activation_dependency: str
    state: str = "planned"

    @property
    def scope(self) -> str:
        return f"gate:personal:{self.operation}"


_PEERS = ("user", "chat", "channel", "self")
_GROUPS = ("chat", "channel")
_CHANNEL = ("channel",)


def _record(
    family: str,
    operation: str,
    sprint: str,
    effect: str,
    methods: str = "",
    peers: tuple[str, ...] = (),
    dependency: str = "runtime_and_work",
) -> CapabilityRecord:
    return CapabilityRecord(
        f"{family}.{operation}",
        family,
        operation,
        sprint,
        effect,
        peers,
        tuple(methods.split()) if methods else (),
        dependency,
    )


